//! Request hardening: same-origin enforcement (CSRF, cross-site WebSocket hijacking) and
//! security response headers.

use axum::extract::Request;
use axum::http::{header, HeaderValue, Method, StatusCode};
use axum::middleware::Next;
use axum::response::{IntoResponse, Response};

use crate::error::ApiError;

/// Rejects state-changing requests and WebSocket upgrades that a browser sent on behalf of
/// another site. Non-browser clients (no `Origin`/`Sec-Fetch-Site`) are not affected.
pub async fn same_origin(request: Request, next: Next) -> Response {
    let safe = matches!(*request.method(), Method::GET | Method::HEAD | Method::OPTIONS);
    let upgrade = request.headers().get(header::UPGRADE).is_some();
    // Public plugin endpoints are meant for other sites and never use the session; sandboxed
    // plugin pages authenticate with plugin tokens only (no cookies).
    let path = request.uri().path();
    let public = path.starts_with("/api/v1/public/");
    let plugin_page =
        is_plugin_endpoint(path) && crate::routes::plugins::plugin_token(request.headers()).is_some();
    if (!safe || upgrade) && !public && !plugin_page && !is_same_origin(request.headers()) {
        return ApiError::new(StatusCode::FORBIDDEN, "cross-origin request refused").into_response();
    }
    next.run(request).await
}

/// `/api/v1/instances/<instance>/plugins/<id>/events/<name>` or `…/plugins/<id>/ws`: the only
/// routes accepting plugin tokens.
fn is_plugin_endpoint(path: &str) -> bool {
    let parts: Vec<&str> = path.split('/').collect();
    match parts.as_slice() {
        ["", "api", "v1", "instances", _, "plugins", _, "events", name] => !name.is_empty(),
        ["", "api", "v1", "instances", _, "plugins", _, "ws"] => true,
        _ => false,
    }
}

fn is_same_origin(headers: &axum::http::HeaderMap) -> bool {
    if let Some(site) = headers.get("sec-fetch-site").and_then(|v| v.to_str().ok()) {
        return matches!(site, "same-origin" | "none");
    }
    let Some(origin) = headers.get(header::ORIGIN).and_then(|v| v.to_str().ok()) else {
        return true;
    };
    let Some(host) = headers.get(header::HOST).and_then(|v| v.to_str().ok()) else {
        return false;
    };
    origin
        .split_once("://")
        .is_some_and(|(_, authority)| authority.eq_ignore_ascii_case(host))
}

/// Rejects requests for unknown host names (DNS rebinding) when `allowed_hosts` is set. The
/// health check is exempt: it reveals nothing and container health checks use `127.0.0.1`.
pub async fn allowed_hosts(
    axum::extract::State(hosts): axum::extract::State<std::sync::Arc<Vec<String>>>,
    request: Request,
    next: Next,
) -> Response {
    if !hosts.is_empty() && request.uri().path() != "/api/v1/health" {
        let host = request
            .headers()
            .get(header::HOST)
            .and_then(|v| v.to_str().ok())
            .unwrap_or("");
        let name = host
            .rsplit_once(':')
            .filter(|(_, port)| port.chars().all(|c| c.is_ascii_digit()))
            .map_or(host, |(h, _)| h);
        if !hosts
            .iter()
            .any(|h| h.eq_ignore_ascii_case(host) || h.eq_ignore_ascii_case(name))
        {
            // Says which name arrived, so a misconfiguration (address typed differently, proxy
            // not passing `Host`) is quick to fix; the caller sent that name itself.
            let shown: String = host.chars().filter(|c| c.is_ascii_graphic()).take(100).collect();
            // At most every 30 s: scanners hit servers by address all the time.
            static LAST_WARNING: std::sync::atomic::AtomicU64 = std::sync::atomic::AtomicU64::new(0);
            let now = std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_secs())
                .unwrap_or_default();
            let last = LAST_WARNING.load(std::sync::atomic::Ordering::Relaxed);
            if now >= last + 30
                && LAST_WARNING
                    .compare_exchange(
                        last,
                        now,
                        std::sync::atomic::Ordering::Relaxed,
                        std::sync::atomic::Ordering::Relaxed,
                    )
                    .is_ok()
            {
                tracing::warn!(host = %shown, "request for a host name not in http.allowed_hosts (further ones are not logged for 30 s)");
            }
            return ApiError::new(
                StatusCode::MISDIRECTED_REQUEST,
                format!("unknown host '{shown}': add it to http.allowed_hosts (JAMES_HTTP__ALLOWED_HOSTS)"),
            )
            .into_response();
        }
    }
    next.run(request).await
}

/// Adds defensive headers to every response. The page's script policy comes from the
/// `<meta>` CSP generated by the web build (with hashes for its inline bootstrap script).
pub async fn headers(request: Request, next: Next) -> Response {
    let mut response = next.run(request).await;
    let h = response.headers_mut();
    h.insert(
        header::X_CONTENT_TYPE_OPTIONS,
        HeaderValue::from_static("nosniff"),
    );
    h.insert(header::X_FRAME_OPTIONS, HeaderValue::from_static("DENY"));
    h.insert(header::REFERRER_POLICY, HeaderValue::from_static("no-referrer"));
    // Responses with their own policy (sandboxed plugin pages) keep it.
    h.entry(header::CONTENT_SECURITY_POLICY)
        .or_insert(HeaderValue::from_static(
            "frame-ancestors 'none'; object-src 'none'; base-uri 'self'",
        ));
    response
}

#[cfg(test)]
mod tests {
    use super::*;

    fn headers(pairs: &[(&'static str, &'static str)]) -> axum::http::HeaderMap {
        let mut map = axum::http::HeaderMap::new();
        for (k, v) in pairs {
            map.insert(*k, HeaderValue::from_static(v));
        }
        map
    }

    #[test]
    fn plugin_endpoints_are_matched_exactly() {
        assert!(is_plugin_endpoint(
            "/api/v1/instances/music/plugins/np/events/current"
        ));
        assert!(is_plugin_endpoint("/api/v1/instances/music/plugins/np/ws"));
        assert!(!is_plugin_endpoint("/api/v1/instances/plugins/plugins/np/config"));
        assert!(!is_plugin_endpoint("/api/v1/instances/music/plugins/np/token"));
        assert!(!is_plugin_endpoint("/api/v1/plugins/np"));
        assert!(!is_plugin_endpoint(
            "/api/v1/instances/music/plugins/np/events/a/b"
        ));
    }

    #[test]
    fn origin_rules() {
        assert!(is_same_origin(&headers(&[])), "non-browser clients");
        assert!(is_same_origin(&headers(&[("sec-fetch-site", "same-origin")])));
        assert!(
            !is_same_origin(&headers(&[("sec-fetch-site", "same-site")])),
            "sibling subdomains"
        );
        assert!(!is_same_origin(&headers(&[("sec-fetch-site", "cross-site")])));
        assert!(is_same_origin(&headers(&[
            ("origin", "https://bot.example"),
            ("host", "bot.example")
        ])));
        assert!(!is_same_origin(&headers(&[
            ("origin", "https://evil.example"),
            ("host", "bot.example")
        ])));
    }
}
